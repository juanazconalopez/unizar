import { expect, type Page, type TestInfo } from '@playwright/test'

export async function checkTrainingSchedule(page: Page, info: TestInfo) {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.clock.install({ time: new Date('2026-09-24T12:00:00+02:00') })
  await page.goto('/')
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Temporadas', exact: true }).click()
  await page.locator('.season-card').filter({ hasText: 'Temporada 2026/2027' }).getByRole('button', { name: /Festivos/ }).click()
  const holidays = page.getByRole('dialog', { name: /Festivos · Temporada 2026/ })
  for (let month = 0; month < 11; month++) await holidays.getByRole('button', { name: 'Mes siguiente' }).click()
  await holidays.getByRole('button', { name: '8', exact: true }).click()
  await holidays.getByRole('button', { name: '22', exact: true }).click()
  await holidays.getByRole('button', { name: 'Guardar festivos', exact: true }).click()

  await page.getByRole('button', { name: 'Gestión', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Entrenamientos', exact: true }).click()
  await page.getByRole('button', { name: 'Generar entrenamientos', exact: true }).click()
  const preview = page.getByRole('dialog', { name: 'Generar entrenamientos' })
  await expect(preview.getByText('Preparando vista previa…')).toHaveCount(0)
  await expect(preview.getByRole('alert')).toHaveCount(0)
  await expect(preview.getByRole('button', { name: /^Generar \d+ entrenamientos$/ })).toBeEnabled()
  await expect(preview.locator('li:has(time[datetime="2026-12-08"])')).toContainText('Festivo')
  await expect(preview.locator('li:has(time[datetime="2026-12-22"])')).toContainText('Festivo')
  await expect(preview.locator('li:has(time[datetime="2026-10-01"])')).toContainText('Ya existe')
  const createCount = await preview.getByRole('button', { name: /^Generar \d+ entrenamientos$/ }).innerText()
  expect(createCount).not.toContain('Generar 0 ')
  await preview.getByRole('button', { name: /^Generar \d+ entrenamientos$/ }).click()
  await expect(preview).toHaveCount(0)
  const card = page.locator('.training-plan-card').filter({ hasText: 'Entrenamiento viernes 25 sept' })
  await expect(card).toContainText('0 ejercicios')
  await card.getByRole('button', { name: /Editar entrenamiento/ }).click()
  await page.getByLabel('Título', { exact: true }).fill('Entrenamiento de continuidad')
  await page.getByLabel('Objetivos', { exact: true }).fill('PLAN PRIVADO: organizar la defensa')
  await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  // La segunda generación no altera los planes existentes ni ofrece duplicados.
  await page.getByRole('button', { name: 'Generar entrenamientos', exact: true }).click()
  await expect(preview.getByRole('button', { name: 'Generar 0 entrenamientos' })).toBeDisabled()
  await expect(preview.locator('li:has(time[datetime="2026-09-25"])')).toContainText('Ya existe')
  await preview.getByRole('button', { name: 'Cancelar', exact: true }).click()

  await page.getByLabel('Ver como').selectOption('player')
  await page.getByRole('button', { name: 'Calendario', exact: true }).click()
  await page.getByRole('button', { name: /^25 de septiembre:/ }).click()
  const training = page.locator('.selected-day-trainings article')
  await expect(training).toContainText('Entrenamiento de continuidad')
  await expect(training).toContainText('19:30–21:30')
  const count = training.locator('.training-attending-count')
  await expect(count).toHaveAccessibleName('0 jugadoras han confirmado su asistencia')
  await expect(page.getByText('PLAN PRIVADO: organizar la defensa')).toHaveCount(0)
  await expect(training.getByText('Borrador')).toHaveCount(0)
  await expect(training.getByRole('button', { name: 'En duda' })).toHaveCount(0)
  await training.getByRole('button', { name: 'Rechazar', exact: true }).click()
  await expect(training.getByLabel('Tu asistencia')).toHaveValue('false')
  await training.getByLabel('Comentario (opcional)').fill('Salgo tarde del trabajo')
  await training.getByRole('button', { name: 'Guardar respuesta', exact: true }).click()
  await expect(training).toContainText('Tu respuesta: Rechazar')
  await expect(count).toHaveAccessibleName('0 jugadoras han confirmado su asistencia')
  await training.getByRole('button', { name: 'Modificar respuesta', exact: true }).click()
  await training.getByLabel('Tu asistencia').selectOption('true')
  await training.getByLabel('Comentario (opcional)').fill('Llego a tiempo')
  await training.getByRole('button', { name: 'Guardar respuesta', exact: true }).click()
  await expect(training).toContainText('Tu respuesta: Asistiré')
  await expect(count).toHaveAccessibleName('1 jugadora ha confirmado su asistencia')
  await expect(count).toContainText('asistirá')
  // Cambiar solo el comentario no incrementa el total.
  await training.getByRole('button', { name: 'Modificar respuesta', exact: true }).click()
  await training.getByLabel('Comentario (opcional)').fill('Llegaré por la puerta principal')
  await training.getByRole('button', { name: 'Guardar respuesta', exact: true }).click()
  await expect(count).toHaveAccessibleName('1 jugadora ha confirmado su asistencia')
  // Retirar una confirmación descuenta una, y volver a confirmarla la recupera.
  await training.getByRole('button', { name: 'Modificar respuesta', exact: true }).click()
  await training.getByLabel('Tu asistencia').selectOption('false')
  await training.getByRole('button', { name: 'Guardar respuesta', exact: true }).click()
  await expect(count).toHaveAccessibleName('0 jugadoras han confirmado su asistencia')
  await training.getByRole('button', { name: 'Modificar respuesta', exact: true }).click()
  await training.getByLabel('Tu asistencia').selectOption('true')
  await training.getByRole('button', { name: 'Guardar respuesta', exact: true }).click()
  await expect(count).toHaveAccessibleName('1 jugadora ha confirmado su asistencia')
  expect(await page.locator('.content').evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: `/tmp/unizar-training-${info.project.name}.png`, fullPage: true })

  // Confirmar un viernes futuro tampoco crea una sesión estadística.
  await page.getByRole('button', { name: 'Mes siguiente', exact: true }).click()
  await page.getByRole('button', { name: /^2 de octubre:/ }).click()
  await training.getByRole('button', { name: 'Asistiré', exact: true }).click()
  await expect(training).toContainText('Tu respuesta: Asistiré')
  await page.getByRole('button', { name: 'Mes anterior', exact: true }).click()
  await page.getByRole('button', { name: /^25 de septiembre:/ }).click()

  await page.clock.setSystemTime(new Date('2026-09-25T20:00:00+02:00'))
  await page.getByLabel('Ver como').selectOption('owner')
  await page.getByRole('button', { name: 'Calendario', exact: true }).click()
  await expect(count).toHaveAccessibleName('1 jugadora ha confirmado su asistencia')
  await page.getByRole('button', { name: 'Asistencia', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Resumen', exact: true }).click()
  const totalSessions = page.getByLabel('Resumen del mes').locator('article').filter({ hasText: 'Entrenamientos' }).locator('.statistics-summary-value strong')
  await expect(totalSessions).toHaveText('4')
  await page.getByRole('button', { name: 'Asistencia', exact: true }).click()
  await page.getByRole('menuitem', { name: /Registrar asistencia/ }).click()
  await expect(page.getByText(/Base de las respuestas:/)).toContainText('1 asistirán')
  const marta = page.getByRole('checkbox', { name: /Marta Sánchez/ })
  await expect(marta).toBeChecked()
  await expect(marta).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Guardar asistencia', exact: true })).toHaveCount(0)
  await expect(page.getByText('Estas previsiones aún no cuentan en las estadísticas.', { exact: false })).toBeVisible()
  // El proceso automático registra al terminar, incluso sin validar en el staff.
  await page.clock.setSystemTime(new Date('2026-09-25T21:30:00+02:00'))
  await page.clock.runFor(1100)
  await expect(page.getByText('Asistencia registrada automáticamente.', { exact: false })).toBeVisible()
  await expect(marta).toBeChecked()
  await expect(page.getByRole('checkbox', { name: /Claudia Pérez/ })).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Guardar asistencia', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Asistencia', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Resumen', exact: true }).click()
  await expect(totalSessions).toHaveText('5')
  await page.getByLabel('Ver como').selectOption('player')
  await page.getByRole('button', { name: 'Calendario', exact: true }).click()
  await expect(training).toContainText('Tu respuesta: Asistiré')
  await expect(training).toContainText('Asistencia registrada')
  await expect(count).toHaveAccessibleName('1 jugadora ha confirmado su asistencia')
  await expect(count).toContainText('confirmada')
  await expect(training.getByRole('button', { name: 'Modificar respuesta' })).toHaveCount(0)

  // El cierre por hora funciona sin un registro del staff y con la página abierta.
  await page.getByRole('button', { name: /^29 de septiembre:/ }).click()
  await training.getByRole('button', { name: 'Asistiré', exact: true }).click()
  await expect(training).toContainText('Tu respuesta: Asistiré')
  await page.clock.setSystemTime(new Date('2026-09-29T21:30:00+02:00'))
  await page.clock.runFor(1000)
  await expect(training.getByRole('button', { name: 'Modificar respuesta' })).toHaveCount(0)
  await expect(training).toContainText('El plazo de respuesta está cerrado')
  expect(errors).toEqual([])
}
