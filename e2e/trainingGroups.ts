import { expect, type Page, type TestInfo } from '@playwright/test'

export async function checkTrainingGroups(page: Page, testInfo: TestInfo) {
  await page.clock.install({ time: new Date('2026-10-21T12:00:00+02:00') })
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const backendCalls: string[] = []
  page.on('request', (request) => { if (/supabase.*\/(rest|functions)\//.test(request.url())) backendCalls.push(request.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Gestión', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Grupos de entrenamiento', exact: true }).click()
  await expect(page.getByText('Toca rehacer los grupos', { exact: true })).toBeVisible()
  await expect(page.locator('.training-group-date-line')).toContainText('29 sept 2026')
  await expect(page.getByLabel('Temporada')).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Reparto', exact: true })).toHaveCount(0)
  await expect(page.getByText(/Creado el/)).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Grupo ROJO' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Grupo BLANCO' })).toBeVisible()
  await page.getByRole('button', { name: 'Generar nuevos grupos' }).click()
  await expect(page.getByText(/Reparto equilibrado:/)).toBeVisible()
  await expect(page.getByLabel('Fecha de inicio')).toHaveValue('2026-10-26')
  await expect(page.locator('.training-group-balance').getByText(/Solo entrenamientos/).first()).toBeVisible()
  await page.getByRole('button', { name: /^Mover a Marta Sánchez al grupo/ }).click()
  await page.getByRole('button', { name: 'Guardar borrador' }).click()
  await expect(page.getByText(/Borrador guardado/)).toBeVisible()
  await expect(page.getByLabel('Fecha de inicio')).toHaveValue('2026-10-26')
  await page.screenshot({ path: `/tmp/unizar-grupos-${testInfo.project.name}-borrador.png`, fullPage: true })

  // El borrador todavía no llega a las jugadoras.
  await page.getByLabel('Ver como').selectOption('player')
  await page.getByRole('button', { name: 'Inicio', exact: true }).click()
  await expect(page.getByRole('region', { name: /grupo de entrenamiento/i })).toHaveCount(0)
  await page.getByRole('button', { name: 'Grupos de entrenamiento', exact: true }).click()
  await expect(page.getByLabel('Temporada')).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Reparto', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Publicar grupos' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Mover a / })).toHaveCount(0)

  await page.getByLabel('Ver como').selectOption('owner')
  await page.getByRole('button', { name: 'Gestión', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Grupos de entrenamiento', exact: true }).click()
  await page.getByRole('button', { name: 'Publicar grupos' }).click()
  const confirmation = page.getByRole('dialog', { name: 'Publicar grupos de entrenamiento' })
  await expect(confirmation).toContainText('26 oct')
  await confirmation.getByRole('button', { name: 'Confirmar publicación' }).click()
  await expect(page.getByText(/Grupos publicados/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Publicar grupos' })).toHaveCount(0)

  await page.getByLabel('Ver como').selectOption('player')
  await page.getByRole('button', { name: /^Avisos/ }).filter({ visible: true }).click()
  const notifications = page.getByRole('dialog', { name: 'Avisos' })
  await expect(notifications.getByRole('button', { name: /Tu grupo de entrenamiento/ })).toHaveCount(2)
  await notifications.getByRole('button', { name: /Tu grupo de entrenamiento/ }).first().click()
  await expect(page.getByRole('heading', { name: 'Grupos de entrenamiento', exact: true })).toBeVisible()
  await expect(page.locator('.training-group-date-line')).toContainText('26 oct 2026')
  await expect(page.getByLabel('Temporada')).toHaveCount(0)
  await expect(page.getByRole('combobox', { name: 'Reparto', exact: true })).toHaveCount(0)
  const ownGroup = page.getByRole('region', { name: /^Grupo (ROJO|BLANCO)$/ }).filter({ has: page.getByText('Marta Sánchez · Tú', { exact: true }) })
  const ownColor = (await ownGroup.getAttribute('aria-label'))!.replace('Grupo ', '')
  const notice = page.getByRole('status', { name: 'Tu grupo en este reparto' })
  await expect(notice).toContainText(`Desde el 26 oct pertenecerás al grupo ${ownColor}`)
  await expect(notice).toContainText(`camiseta ${ownColor === 'ROJO' ? 'roja' : 'blanca'}`)
  for (const color of ['ROJO', 'BLANCO']) {
    const group = page.getByRole('region', { name: `Grupo ${color}` })
    await expect(group.getByRole('heading', { name: /Delanteras|Línea|Sin posición/ })).toHaveCount(0)
    await expect(group.getByText(/Equipo A|Equipo B|Unizar Femenino|Mixto|Solo entrenamientos/)).toHaveCount(0)
    const names = (await group.getByRole('listitem').allTextContents()).map((name) => name.replace(' · Tú', ''))
    expect(names).toEqual([...names].sort((a, b) => a.localeCompare(b, 'es')))
  }
  await page.screenshot({ path: `/tmp/unizar-grupos-${testInfo.project.name}-jugadora.png`, fullPage: true })
  await expect(notice).toContainText('Desde el 26 oct pertenecerás al grupo')
  await expect(notice).not.toContainText('Perteneces al grupo')
  const startDate = await page.locator('.training-group-date-line').boundingBox()
  expect(startDate!.x + startDate!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
  expect(errors).toEqual([])
  expect(backendCalls).toEqual([])
}
