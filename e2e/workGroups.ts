import { expect, type Page, type TestInfo } from '@playwright/test'

export async function checkWorkGroups(page: Page, testInfo: TestInfo) {
  await page.clock.setFixedTime(new Date('2026-10-21T12:00:00+02:00'))
  const errors: string[] = []
  const backendCalls: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => { if (/supabase.*\/(rest|functions)\//.test(request.url())) backendCalls.push(request.url()) })
  await page.goto('/')
  await page.getByRole('button', { name: 'Gestión', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Grupos', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Grupos', exact: true })).toBeVisible()
  await page.screenshot({ path: `/tmp/unizar-organizacion-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: /EL EQUIPO FUERA DEL CAMPO/ }).click()
  await expect(page.getByRole('region', { name: /^Grupo de trabajo / })).toHaveCount(9)
  await expect(page.getByText('43 integrantes · 9 grupos de trabajo')).toBeVisible()
  await page.screenshot({ path: `/tmp/unizar-trabajo-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Editar Material', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Editar Material', exact: true })
  await editor.getByLabel('Grupo de Claudia Calvo', { exact: true }).selectOption('botiquin')
  await editor.getByLabel('Persona del equipo').selectOption('demo-player')
  await editor.getByRole('button', { name: 'Añadir al grupo' }).click()
  await page.screenshot({ path: `/tmp/unizar-trabajo-editor-${testInfo.project.name}.png`, fullPage: true })
  await editor.getByRole('button', { name: 'Guardar grupo' }).click()
  await expect(page.getByRole('region', { name: 'Grupo de trabajo Botiquín' })).toContainText('Claudia Calvo')
  await page.getByRole('button', { name: 'Todos los grupos' }).click()
  await page.getByRole('button', { name: /APRENDER DE CADA PARTIDO/ }).click()
  const rows = page.locator('.video-match-row')
  await expect(rows).toHaveCount(15)
  await expect(rows.first()).toContainText('Merchan')
  await expect(rows.first()).toContainText('Derbi inicial · asignación fija')
  await expect(rows.filter({ hasText: 'Jornada 2' })).toHaveCount(2)
  await rows.first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: `/tmp/unizar-video-${testInfo.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Editar asignaciones' }).click()
  await expect(rows.first().getByRole('combobox')).toHaveCount(0)
  await rows.nth(1).getByRole('combobox').selectOption('material')
  await page.getByRole('button', { name: 'Guardar asignaciones' }).click()
  await expect(rows.nth(1)).toContainText('Material')

  await page.getByLabel('Ver como').selectOption('player')
  await page.getByRole('button', { name: 'Grupos', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Grupos de trabajo', exact: true }).click()
  await expect(page.getByText('Tu grupo de trabajo').locator('..')).toContainText('Material')
  await expect(page.getByRole('region', { name: 'Grupo de trabajo Material' })).toContainText('Marta SánchezTú')
  await expect(page.locator('.work-groups-grid').getByRole('button')).toHaveCount(0)
  await page.getByRole('button', { name: 'Grupos', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Asignación de vídeo análisis', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Editar asignaciones' })).toHaveCount(0)
  await page.getByLabel('Ver grupo').selectOption('own')
  await expect(page.locator('.video-match-row')).not.toHaveCount(0)
  await expect(page.locator('.video-pool-badge').filter({ hasNotText: 'Material' })).toHaveCount(0)
  await page.screenshot({ path: `/tmp/unizar-video-jugadora-${testInfo.project.name}.png`, fullPage: true })
  expect(await page.locator('.video-match-row').evaluateAll((items) => items.every((item) => item.getBoundingClientRect().right <= window.innerWidth))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
  expect(errors).toEqual([])
  expect(backendCalls).toEqual([])
}
